def section_text(name: str) -> str:
    key = ALIASES.get(utils.normalize(name).lower())
    if not key or key not in GUIDE:
        return "❌ این نوع راهنما وجود ندارد.\n\nراهنما، بن، سکوت، قفل، آمار، گزارش، مدیریت، گروه، کال، سرگرمی یا پیشرفته را امتحان کنید."
    section = GUIDE[key]
    lines = [section["title"], "━━━━━━━━━━━━━━━━━━━━", ""]
    for label, desc, example in section["items"]:
        lines.append(f"• {label} — {desc}")
        lines.append(_quote_command(example))
        lines.append("")
    lines.append("بازگشت: `راهنما`")
    return "\n".join(lines).strip()


def _guide_entry(ctx):
    if not ctx.is_group or not ctx.guid:
        return None
    meta = ctx.g.setdefault("guide_message_meta", {})
    entry = meta.get("shared")
    if isinstance(entry, str):
        entry = {"message_id": entry, "updated_at": 0.0}
        meta["shared"] = entry
    return entry if isinstance(entry, dict) else None


async def _store_and_send(ctx, text):
    result = await ctx.reply(text, reply=False)
    mid = ctx.api.result_message_id(result)
    if ctx.is_group and ctx.guid and mid:
        # Keep backward-compatible per-author storage as well as richer
        # group-level metadata. The effective guide message is group-scoped.
        ctx.g.setdefault("guide_message_ids", {})["shared"] = str(mid)
        if ctx.author:
            ctx.g["guide_message_ids"][str(ctx.author)] = str(mid)
        ctx.g.setdefault("guide_message_meta", {})["shared"] = {
            "message_id": str(mid),
            "updated_at": __import__("time").time(),
        }
        db.save("groups")
    return result


async def _edit_or_send(ctx, text):
    if ctx.is_group and ctx.guid:
        now = __import__("time").time()
        entry = _guide_entry(ctx)
        if entry is None:
            old = (ctx.g.get("guide_message_ids") or {}).get("shared")
            if old is None and ctx.author:
                old = (ctx.g.get("guide_message_ids") or {}).get(str(ctx.author))
            if old:
                entry = {"message_id": str(old), "updated_at": 0.0}
                ctx.g.setdefault("guide_message_meta", {})["shared"] = entry
        if entry and entry.get("message_id"):
            mid = str(entry["message_id"])
            age = now - float(entry.get("updated_at") or 0)
            if age < float(getattr(__import__("config"), "GUIDE_NEW_MESSAGE_AFTER_SECONDS", 180)):
                try:
                    await ctx.api.edit(ctx.guid, mid, text)
                    entry["updated_at"] = now
                    ctx.g.setdefault("guide_message_ids", {})["shared"] = mid
                    if ctx.author:
                        ctx.g["guide_message_ids"][str(ctx.author)] = mid
                    db.save("groups")
                    return True
                except Exception:
                    pass
            elif age >= float(getattr(__import__("config"), "GUIDE_NEW_MESSAGE_AFTER_SECONDS", 180)):
                # بعد از سه دقیقه عمداً یک پیام راهنمای جدید می‌سازیم.
                await _store_and_send(ctx, text)
                return True
    await _store_and_send(ctx, text)
    return True


async def handle(ctx) -> bool:
    text = utils.normalize(ctx.text)
    if text in ("راهنما", "دستورات", "کمک", "help"):
        await _edit_or_send(ctx, menu_text())
        return True
    m = re.fullmatch(r"راهنما\s+(.+)", text, re.S)
    if m:
        arg = m.group(1).strip()
        if arg.isdigit():
            return False  # keep legacy «راهنما 2/3/...» paging in misc.py
        await _edit_or_send(ctx, section_text(arg))
        return True
    return False
