# Click-to-answer quiz / poll state
#
# FBI runs as a SplusLib user-account client. Native Bot CallbackQuery buttons
# are bot-oriented in the SplusLib reference, so for a user account we use the
# supported reply-keyboard buttons. Tapping an option sends that option as a
# normal message, which the handler below consumes as the answer.
_ACTIVE_CHOICE_SESSIONS = {}


def _make_quiz_button(label):
    try:
        from spluslib._base import Button
        # Reply buttons work for an account session and keep the quiz click-based.
        return Button.text(str(label)[:142], resize=True, single_use=True, selective=False)
    except Exception as exc:
        raise RuntimeError(f"دکمه انتخاب SplusLib در دسترس نیست: {exc}") from exc


async def _user_link(api, guid, chat_id=None, fallback_name="کاربر"):
    gid = str(guid or "")
    if not gid:
        return fallback_name
    try:
        info = await api.user_info(gid, chat_hint=chat_id, force=True)
    except Exception:
        info = None
    name = api_mod.name_of(info) if info else fallback_name
    username = api_mod._val(info, "username", "user_name", default="") if info else ""
    name = str(name or fallback_name or "کاربر").replace("[", r"\[").replace("]", r"\]")
    if username:
        return f"[{name}](https://splus.ir/{str(username).lstrip('@')})"
    # SplusLib's message parser explicitly documents tg://user?id= links.
    return f"[{name}](tg://user?id={gid})"


def _choice_keyboard(options):
    rows = []
    row = []
    for option in options:
        row.append(_make_quiz_button(option))
        if len(row) == 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    return rows


