def _unique_options(correct, pool, size=4):
    correct = str(correct)
    vals = [str(x) for x in pool if str(x) != correct]
    random.shuffle(vals)
    return [correct] + vals[:max(1, size - 1)]


def _shuffle_quiz(options, correct_index=0):
    options = list(options)
    correct_value = options[int(correct_index)]
    random.shuffle(options)
    return options, options.index(correct_value)


