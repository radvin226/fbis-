async def _handle_choice(ctx) -> bool:
    """Consume a reply-keyboard quiz/poll answer before normal commands run."""
    state = _ACTIVE_CHOICE_SESSIONS.get(str(ctx.guid))
    if not state:
        return False
    # Keep stale questionnaires from trapping ordinary messages forever.
    if time.time() - float(state.get("created_at") or 0) > 15 * 60:
        _ACTIVE_CHOICE_SESSIONS.pop(str(ctx.guid), None)
        return False

    text = str(ctx.text or "").strip()
    try:
        index = state["options"].index(text)
    except ValueError:
        return False

    user_id = str(ctx.author or "")
    if not user_id:
        return False
    answers = state.setdefault("answers", {})
    if user_id in answers:
        name = await ctx.target_link(user_id)
        await ctx.reply(f"ℹ️ {name} قبلاً در این مورد پاسخ داده است.")
        return True
    answers[user_id] = index

    user_link = await ctx.target_link(user_id, fallback_name="کاربر")
    option = state["options"][index]
    if state.get("is_quiz"):
        correct = int(state["correct"])
        if index == correct:
            body = f"✅ درست! {user_link}\nپاسخ شما: «{option}»"
        else:
            answer = state["options"][correct]
            body = (
                f"❌ نادرست! {user_link}\n"
                f"پاسخ شما: «{option}»\n"
                f"✅ پاسخ صحیح: «{answer}»"
            )
    else:
        counts = [0] * len(state["options"])
        for chosen in answers.values():
            if 0 <= int(chosen) < len(counts):
                counts[int(chosen)] += 1
        body = (
            f"📊 رأی {user_link} ثبت شد.\n"
            f"گزینه شما: «{option}»\n\n"
            + "\n".join(
                f"{i + 1}. {opt} — {counts[i]} رأی"
                for i, opt in enumerate(state["options"])
            )
        )
    await ctx.reply(body)
    return True


