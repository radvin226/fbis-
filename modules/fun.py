def _generated_category_hard(question, correct_pool, distractor_pool=None):
    correct = str(random.choice(tuple(correct_pool)))
    # For classification questions, distractors must come from outside the
    # correct category; otherwise every option can accidentally be correct.
    pool = list(distractor_pool or [])
    distractors = [str(x) for x in pool if str(x) != correct]
    random.shuffle(distractors)
    options = [correct] + distractors[:3]
    if len(options) < 4:
        fallback = [x for x in ADVANCED_WORDS if str(x) != correct and str(x) not in options]
        random.shuffle(fallback)
        options.extend(fallback[:4-len(options)])
    return question, options[:4], 0


