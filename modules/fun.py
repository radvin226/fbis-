async def _send_quiz(ctx, question, options, correct=0, *, spoiler_answer=None):
    clean = [str(x).strip()[:120] for x in options if str(x).strip()]
    if len(clean) < 2:
        await ctx.err("تعداد گزینه‌های آزمون کافی نیست.")
        return True
    correct = int(correct)
    if not 0 <= correct < len(clean):
        await ctx.err("پاسخ صحیح آزمون نامعتبر است.")
        return True
    clean, correct = _shuffle_quiz(clean, correct)
    try:
        result = await ctx.api.send_poll(
            ctx.guid, str(question), clean,
            quiz=True, correct_option_index=correct, is_anonymous=False,
            multiple_choice=False, close_period=600, reply_to=ctx.message_id or None,
        )
        if not isinstance(result, dict) or not result.get("native"):
            raise RuntimeError("quiz was not sent as a native poll")
        if spoiler_answer:
            await ctx.api.send_spoiler(
                ctx.guid,
                "💡 پاسخ: ",
                spoiler_answer,
                reply_to=ctx.message_id or None,
            )
    except Exception as exc:
        await ctx.err(f"ارسال کوییز واقعی ناموفق بود: {type(exc).__name__}")
    return True


